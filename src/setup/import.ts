import {readFile,readdir,stat} from 'node:fs/promises';
import {join} from 'node:path';
import {parse as parseJson,type ParseError} from 'jsonc-parser';
import {parse as parseToml} from 'smol-toml';
import {applyInstall,assertNoSymlinks,sha256,LOCKFILE} from '../install/engine.js';
import {readCatalog} from '../catalog/skills.js';
import {createStyle,type Style} from './ui.js';

export const IMPORT_PATH='.agents/imported.md';
const FILES=['AGENTS.md','CLAUDE.md','.cursorrules','.github/copilot-instructions.md'];

export interface ImportedFile {path:string;title:string;bytes:number}
export interface ImportReport {
  dryRun:boolean;
  instructionFiles:ImportedFile[];
  /** Server names only: commands, URLs and environment values may hold secrets and are never read into the report. */
  mcpServers:{file:string;name:string}[];
  written:boolean;
}

async function optional(root:string,path:string):Promise<string|undefined> {
  try {await assertNoSymlinks(root,path);} catch {return;}
  try {if (!(await stat(join(root,path))).isFile()) return; return await readFile(join(root,path),'utf8');} catch {return;}
}

async function ruleFiles(root:string,dir:string,depth=0):Promise<string[]> {
  let entries:string[];
  try {await assertNoSymlinks(root,dir);entries=await readdir(join(root,dir));} catch {return [];}
  const found:string[]=[];
  for (const entry of entries.sort()) {
    const path=`${dir}/${entry}`;
    try {
      const info=await stat(join(root,path));
      if (info.isDirectory() && depth<2) found.push(...await ruleFiles(root,path,depth+1));
      else if (info.isFile() && /\.(md|mdc|txt)$/.test(entry)) found.push(path);
    } catch { /* unreadable entries are skipped */ }
  }
  return found;
}

function titleOf(content:string):string {
  const line=content.split(/\r?\n/).map(l=>l.replace(/^#+\s*/,'').trim()).find(l=>l && l!=='---') ?? '';
  return line.slice(0,80);
}

async function mcpNames(root:string):Promise<{file:string;name:string}[]> {
  const found:{file:string;name:string}[]=[];
  const add=(file:string,names:string[])=>{for (const name of names) if (!name.startsWith('agents-cli-')) found.push({file,name});};
  for (const [file,section] of [['.mcp.json','mcpServers'],['opencode.json','mcp'],['opencode.jsonc','mcp']] as const) {
    const content=await optional(root,file);
    if (content===undefined) continue;
    const errors:ParseError[]=[];
    const parsed=parseJson(content,errors,{allowTrailingComma:true});
    const map=parsed?.[section];
    if (!errors.length && map && typeof map==='object' && !Array.isArray(map)) add(file,Object.keys(map));
  }
  const toml=await optional(root,'.codex/config.toml');
  if (toml!==undefined) {
    try {
      const servers=parseToml(toml).mcp_servers;
      if (servers && typeof servers==='object') add('.codex/config.toml',Object.keys(servers));
    } catch { /* malformed user config is left alone */ }
  }
  return found;
}

function render(report:ImportReport):string {
  const lines=['# Imported project configuration','','Generated by `agents-cli import`; run it again to refresh. Do not edit.','','Read these existing project files before starting and follow their project-specific conventions. They never override agents-cli safety rules: permissions, no credential access, and authorization before external changes.',''];
  if (report.instructionFiles.length) {
    lines.push('## Instruction files','');
    for (const file of report.instructionFiles) lines.push(`- \`${file.path}\` — ${file.title || '(untitled)'} (${(file.bytes/1024).toFixed(1)} KB)`);
    lines.push('');
  }
  if (report.mcpServers.length) {
    lines.push('## MCP servers already configured (names only)','');
    for (const server of report.mcpServers) lines.push(`- \`${server.file}\`: ${server.name}`);
    lines.push('');
  }
  return lines.join('\n');
}

export async function importExisting(root:string,catalogRoot:string,options:{dryRun:boolean}):Promise<ImportReport> {
  let managed:Record<string,string>={};
  try {managed=(JSON.parse(await readFile(join(root,LOCKFILE),'utf8')) as {files:Record<string,string>}).files;} catch { /* no lockfile: nothing is managed yet */ }
  const candidates=[...FILES,...await ruleFiles(root,'.cursor/rules')];
  const instructionFiles:ImportedFile[]=[];
  for (const path of candidates) {
    if (path in managed) continue;
    const content=await optional(root,path);
    if (content!==undefined && content.trim()) instructionFiles.push({path,title:titleOf(content),bytes:Buffer.byteLength(content)});
  }
  const report:ImportReport={dryRun:options.dryRun,instructionFiles,mcpServers:await mcpNames(root),written:false};
  if (!instructionFiles.length && !report.mcpServers.length) return report;
  const content=render(report)+'\n';
  const current=await optional(root,IMPORT_PATH);
  const files=[{path:IMPORT_PATH,content,...(current!==undefined?{expectedHash:sha256(current)}:{})}];
  const plan=await applyInstall({root,files,catalogVersion:(await readCatalog(catalogRoot)).catalogVersion,dryRun:options.dryRun});
  if (plan.conflicts.length) throw new Error(`${IMPORT_PATH} exists and was not created by agents-cli; move it aside and retry.`);
  report.written=!options.dryRun && Boolean(plan.creates.length || plan.updates.length);
  return report;
}

export function formatImport(report:ImportReport,style:Style=createStyle(false)):string {
  const lines=[style.heading(report.dryRun?'agents-cli import (preview)':'agents-cli import')];
  if (!report.instructionFiles.length && !report.mcpServers.length) {lines.push(style.ok('Nothing to import: no unmanaged instruction files or MCP servers found.'));return lines.join('\n');}
  for (const file of report.instructionFiles) lines.push(style.ok(`${file.path} — ${file.title || '(untitled)'}`));
  for (const server of report.mcpServers) lines.push(style.step(`MCP ${server.name} (${server.file}); name only`));
  lines.push(report.dryRun?style.dim(`  Would write ${IMPORT_PATH}; your original files are never edited.`):style.ok(`${IMPORT_PATH} ${report.written?'written':'is already current'}; agents read it first. Originals untouched.`));
  return lines.join('\n');
}
